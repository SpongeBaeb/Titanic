/** 노라의 배경 이야기. 마지막 문단은 이 판에서 편지가 어떻게 됐는지에 따라 달라진다(편지 기록이 없으면 중립 문단) */
export function noraStory(extras: Record<string, unknown>): { title: string; paras: string[]; fiction: string } {
  const w1 = (extras.w1 ?? {}) as { letter?: string; outcome?: string };
  const survived = extras.w2Survived === true;
  const lost = extras.letterLost === true;
  let last: string;
  if (w1.letter === 'given' && survived && !lost) {
    last = '그날 난간에서 노라는 편지 한 통을 당신의 주머니에 밀어 넣었습니다. 편지는 5월의 어느 날 클레어 주의 한 부엌에 닿았습니다. 어머니는 봉투를 뜯기 전에 한참 앞치마에 손을 문질렀다고 합니다. 노라가 열지 못한 편지는, 끝내 어머니의 서랍에서 노라 몫으로 남았습니다.';
  } else if (w1.letter === 'given') {
    last = '그날 난간에서 노라는 편지 한 통을 당신의 주머니에 밀어 넣었습니다. 그 편지는 어머니에게 닿지 못했습니다. 클레어 주의 부엌에서는 그해 여름이 지나도록 아침마다 빵을 하나 더 구웠다고 합니다.';
  } else if (w1.outcome === 'let_go') {
    last = '노라는 어머니가 준 편지를 열지 못한 채 바다에 들어갔습니다. 어머니는 끝내 딸이 그 편지를 읽었는지 알지 못했습니다.';
  } else {
    last = '노라는 어머니가 준 편지를 열지 못한 채 난간을 놓았습니다. 클레어 주의 부엌에서는 그해 여름이 지나도록 아침마다 빵을 하나 더 구웠다고 합니다.';
  }
  return {
    title: '노라의 이야기',
    paras: [
      '노라는 1888년 아일랜드 서쪽 클레어 주의 작은 해안 마을에서 태어났습니다. 아버지는 몇 해 전 겨울 폐병으로 세상을 떠났고, 집에는 어린 동생이 셋 남았습니다. 어머니는 새벽마다 소다빵을 구웠고, 노라는 그 냄새로 아침을 알았습니다.',
      '브루클린에서 빵집 일을 하는 언니가 뱃삯을 보내 왔습니다. 노라는 가고 싶지 않았습니다. 동생들과 어머니 곁을 지키고 싶었지만, 집에는 그녀의 임금이 필요했습니다.',
      '떠나기 전날 밤 마을에서는 아메리칸 웨이크가 열렸습니다. 이민 가는 사람을 다시 못 볼 사람처럼 보내는 잔치였습니다. 어머니는 밤새 한 번도 노라와 눈을 맞추지 못했습니다. 다음 날 아침 두 사람은 다퉜습니다. 노라는 “나는 가겠다고 한 적 없어요” 했고, 어머니는 “가라. 가서 편지나 보내라”고만 했습니다. 서로 안아 보지도 못한 채 헤어졌습니다.',
      '어머니는 그날 밤 편지를 한 통 써서 노라의 외투 안감에 꿰매 두었습니다. 노라는 그 편지를 열면 정말 떠난 것이 될 것 같아 배 위에서도 열지 못했습니다. 대신 어머니께 사과하는 편지를 쓰기 시작했습니다.',
      last,
    ],
    fiction: '노라는 실존 인물이 아닙니다. 1912년 4월 퀸스타운에서 3등석에 오른 수많은 이민자들의 이야기를 모아 만든 이름입니다.',
  };
}
